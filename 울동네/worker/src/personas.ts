export function pickPersonaStyle(excludeId?: number | null): PersonaStyle {
  const candidates = excludeId
    ? PERSONA_STYLES.filter((p) => p.id !== excludeId)
    : PERSONA_STYLES;
  const idx = Math.floor(Math.random() * candidates.length);
  return candidates[idx];
}
