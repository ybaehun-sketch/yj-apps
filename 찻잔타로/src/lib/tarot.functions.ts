const GEMINI_MODELS = [
  "gemini-3.5-flash-lite",
  "gemini-3.1-flash-lite",
  "gemini-flash-lite-latest",
] as const;

// 제미나이(GEMINI_API_KEY) 1순위 + 3중 예비 모델 자동 전환, 없을 시 OPENAI_API_KEY 보조 호출.
async function ask(instructions: string, history: Msg[], maxTokens = 800) {
  const geminiKey = (process.env["GEMINI_API_KEY"] || process.env["GOOGLE_API_KEY"])?.trim();
  if (geminiKey) {
    let lastStatus = 500;
    for (const model of GEMINI_MODELS) {
      let res: Response | null = null;
      try {
        res = await fetch(
          `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent`,
          {
            method: "POST",
            headers: {
              "Content-Type": "application/json",
              "x-goog-api-key": geminiKey,
            },
            body: JSON.stringify({
              systemInstruction: { parts: [{ text: instructions }] },
              contents: history.map((m) => ({
                role: m.role === "assistant" ? "model" : "user",
                parts: [{ text: m.content }],
              })),
              generationConfig: {
                maxOutputTokens: Math.max(maxTokens, 800) + 1500,
              },
            }),
          },
        );
      } catch (e) {
        console.error("Gemini fetch error", model, e);
        continue;
      }
      if (!res.ok) {
        lastStatus = res.status;
        console.error("Gemini error", model, res.status, (await res.text()).slice(0, 500));
        if (res.status === 429 || res.status >= 500) continue;
        break;
      }
      const json = (await res.json()) as {
        candidates?: { content?: { parts?: { text?: string }[] } }[];
      };
      const text = (json.candidates?.[0]?.content?.parts ?? [])
        .map((p) => p.text ?? "")
        .join("")
        .trim();
      if (text) return text;
    }
    if (lastStatus === 402 || lastStatus === 403)
      throw new Error("AI 상담 크레딧이 부족해요. 잠시 후 다시 시도해 주세요.");
    if (lastStatus === 429)
      throw new Error("상담 요청이 많아요. 잠시 후 다시 시도해 주세요.");
    throw new Error("상담사가 잠시 자리를 비웠어요. 다시 시도해 주세요.");
  }

  const apiKey = process.env["OPENAI_API_KEY"];
  if (!apiKey) throw new Error("상담사가 잠시 자리를 비웠어요. 다시 시도해 주세요.");
  let res: Response;
  try {
    res = await fetch("https://api.openai.com/v1/responses", {
      method: "POST",
      headers: { "Content-Type": "application/json", Authorization: `Bearer ${apiKey}` },
      body: JSON.stringify({
        model: "gpt-5.4-mini",
        instructions,
        // 행간·장면을 먼저 짚도록 가벼운 추론을 켠다. 추론 토큰이 답변을 잘라먹지 않게 여유를 크게 둔다.
        reasoning: { effort: "low" },
        max_output_tokens: Math.max(maxTokens, 800) + 2000,
        input: history.map((m) => ({ role: m.role, content: m.content })),
      }),
    });
  } catch (e) {
    console.error(e);
    throw new Error("상담사가 잠시 자리를 비웠어요. 다시 시도해 주세요.");
  }
  if (!res.ok) {
    console.error("OpenAI error", res.status, (await res.text()).slice(0, 500));
    if (res.status === 402 || res.status === 403) throw new Error("AI 상담 크레딧이 부족해요. 잠시 후 다시 시도해 주세요.");
    if (res.status === 429) throw new Error("상담 요청이 많아요. 잠시 후 다시 시도해 주세요.");
    throw new Error("상담사가 잠시 자리를 비웠어요. 다시 시도해 주세요.");
  }
  const text = extractText(await res.json());
  if (!text) throw new Error("상담사가 잠시 자리를 비웠어요. 다시 시도해 주세요.");
  return text;
}

